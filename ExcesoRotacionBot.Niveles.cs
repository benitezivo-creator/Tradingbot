        // Evalúa si un precio dado está cerca de algún nivel fijo dentro de una tolerancia en ticks
        private bool EstaCercaDeNivelFijo(double precio, double toleranciaTicks, out double nivelCercano)
        {
            nivelCercano = 0.0;
            double distanciaMaxima = toleranciaTicks * TickSize;

            // Seleccionar conjunto según rango de precio actual
            double[] niveles = precio > 12000 ? NivelesFijosConjunto1 : NivelesFijosConjunto2;

            double menorDistancia = double.MaxValue;
            double mejorNivel = 0.0;

            for (int i = 0; i < niveles.Length; i++)
            {
                double distancia = Math.Abs(precio - niveles[i]);
                if (distancia < menorDistancia)
                {
                    menorDistancia = distancia;
                    mejorNivel = niveles[i];
                }
            }

            if (menorDistancia <= distanciaMaxima)
            {
                nivelCercano = mejorNivel;
                return true;
            }

            return false;
        }
    }
